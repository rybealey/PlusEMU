-- pixelrp: proper names for every piece in the Clothing Store.
--
-- 2445 pieces, from a capture of the live shelf. Almost all of them were
-- showing an imported placeholder ("Staff 3499" - the figuredata set id);
-- the rest were showing a raw set name ("Gatsby", "Hair U Academiadollhairdo").
--
-- How the match works, and why it is done in SQL. The store shows
-- display_name when it is set and otherwise tidies clothing_name: strip a
-- leading "clothing_", split on underscores, capitalise each word. Nothing
-- has ever written display_name, so every piece is currently on a tidied
-- name - which means the shelf label is a usable key, but only if the tidy
-- is reversed case-insensitively. The same label comes from either
-- clothing_staff_3499 or staff_3499, and hair_U_academiadollhairdo shows as
-- "Hair U Academiadollhairdo" with capitals the tidy does not preserve. So
-- the key is rebuilt from clothing_name here rather than guessed offline.
--
-- Only pieces whose display_name is NULL are given one, so this is
-- idempotent and will never overwrite a name set by hand since the capture.
-- The counts at the end are a receipt: anything that did not match is
-- listed rather than passed over in silence.

CREATE TEMPORARY TABLE `rp_clothing_rename` (
  -- the lowercased label the shelf was showing
  `shelf_key` varchar(120) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL,
  `proposed` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL,
  PRIMARY KEY (`shelf_key`)
) ENGINE=InnoDB;

