-- pixelrp: Bsstonino's 872 unnamed furni get English names.
--
-- 122 imported the pack's eleven sub-packs with the names its manifests
-- carried, and for these that was only the bundle number - 'Furni 2111',
-- 'Furni 1939' - because the download has no names at all. Each is named here
-- for what its icon shows: a Dark Velvet Sofa, a Clawfoot Bathtub, a Genie
-- Lamp, Kitchen Counter 1 to 4. Pieces that are variants of one another are
-- numbered in bundle order (Framed Picture, Framed Picture 2...), so no two in
-- the pack share a name.
--
-- The name goes on the catalog row and the furniture row's public_name; the
-- same names go to FurnitureData through
-- nitro/overrides/gamedata-override/FurnitureData.json, which is what rooms,
-- backpacks and the infostand read, with the name as the description.
--
-- Rows are matched by furniture id (= sprite, 122) and classname together, so
-- nothing else can be caught. Idempotent.

