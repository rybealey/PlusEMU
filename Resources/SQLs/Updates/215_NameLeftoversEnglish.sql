-- pixelrp: 154 furni whose names ended in a leftover 'Name' get English ones.
--
-- Their packs name each piece by a lookup key (lyvo_2_frosk_name,
-- VanTassel_Banquete_name) and keep the words in a text file the downloads did
-- not include, so the import titled them from the key: 'Lyvo 2 Frosk Name',
-- 'Vantassel Banquete Name', and in places a machine translation of it
-- ('Vantassel Bank' for banca, a bench; 'Desktop' for escritorio, a desk).
-- Each is named here for what it is, from its icon where the pack drew one and
-- from its classname where the icon is only the VAN TASSEL logo: Lyvo 2's
-- Norwegian garden set (frosk a Frog, snegle a Snail, kjott Raw Meat), the
-- Spanish Harry Potter set (el_fraile_gordo The Fat Friar, sauceboxeador the
-- Whomping Willow, pensadero the Pensieve), Castelobruxo's Brazilian statues
-- (Boitata, Uirapuru, Yara) and the rest.
--
-- The name goes on the catalog row and the furniture row's public_name; the
-- same names go to FurnitureData through
-- nitro/overrides/gamedata-override/FurnitureData.json, which is what rooms,
-- backpacks and the infostand read - with the name as the description, in
-- place of the leftover 'X Desc'.
--
-- Rows are matched by furniture id (= sprite in these packs: 92, 94, 122) and
-- classname together, so nothing else can be caught. Idempotent.

DROP TABLE IF EXISTS `_nl_name`;
CREATE TABLE `_nl_name` (`id` INT NOT NULL PRIMARY KEY, `item_name` VARCHAR(70) NOT NULL, `name` VARCHAR(100) NOT NULL)
    ENGINE=InnoDB DEFAULT CHARSET=latin1;
