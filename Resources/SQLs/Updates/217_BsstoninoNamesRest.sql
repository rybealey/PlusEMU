-- pixelrp: the rest of Bsstonino's numbered furni get English names.
--
-- 216 named the 872 pieces the import had titled 'Furni 2111'; these 1023 were
-- titled 'Bsstonino Furni 2266' - the same missing names with the pack in
-- front, nearly all of them on sub-pages 1 and 10. Each is named for what its
-- icon shows: a Ski Lift Chair, a Husky, a Spiral Staircase, Sash Window 1 to
-- 11, the house-elves and goblins. Variants are numbered in bundle order, and
-- no name repeats anywhere in the pack.
--
-- Two more came with names that were not English or not a name at all - 'Tejado 9'
-- (a Wooden Roof Beam) and 'Bsstonino Furnidinarnia' (a Narnia Dwarf).
--
-- A few icons show only a placeholder - the pack's BSS logo, a red T - and
-- those pieces are named for the icon until someone sees them in a room.
--
-- The name goes on the catalog row and the furniture row's public_name; the
-- same names go to FurnitureData through
-- nitro/overrides/gamedata-override/FurnitureData.json, which is what rooms,
-- backpacks and the infostand read, with the name as the description.
--
-- Rows are matched by furniture id (= sprite, 122) and classname together, so
-- nothing else can be caught. Idempotent.

