-- 287 went too far: it raised every plain furni to all the looks its art
-- draws, including 211 that could already be clicked and whose counts were
-- right. Somebody had set those on purpose - many of them by hand in the
-- Function tool (hygge_c25_floor1 was taken DOWN to 3 by staff, and 287 put it
-- up to 4) - and an animation is not always a click state: the Washing Machine
-- draws its cats moving, the same cats still, and its door shut, and came out
-- of 287 with three clicks where it should have two.
--
-- So this puts back the count each of those had before 287: every furni 287
-- raised that already had 2 or more, and every one whose count staff had set
-- in the Function tool. Only the furni that could not be clicked at all (count
-- 0 or 1, never set) keep 287's fix. Where two rows draw the same art and had
-- different counts, both get the higher one - the one somebody set.
--
-- Each row goes back only if it still holds 287's value, so anything changed
-- since is left alone.
--
-- And a furni can now name the states a click goes through, for art whose
-- looks are not all click states: `click_states`, a comma list, empty for
-- everything else (InteractorGenericSwitch cycles it instead of 0 .. count-1).
-- The Washing Machine is the first: door open with the cats moving <-> door
-- shut, skipping the cats sitting still.

ALTER TABLE `furniture`
    ADD COLUMN `click_states` VARCHAR(64) NOT NULL DEFAULT '';

