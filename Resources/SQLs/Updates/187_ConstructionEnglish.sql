-- pixelrp: Builders > Construction reads in English.
--
-- The pack came in with Spanish page names (Bloque pequeño, Cono, Pequeño,
-- Redondeado, Agua, Arena, Plaqueta...), Spanish tile names (Baldosa Iluminada
-- Rosa is the Pink Light-Up Tile), French classnames behind the Custom
-- Alphabets (arctique, dinerrouge) and everything else named straight from its
-- classname - Bc Block Water, Bc Alpha 1 A, Escalier 26 Yvess. 93 copied those
-- names into the shop as they were.
--
-- Here every one of its 233 pieces takes a plain English name - Water Block,
-- Letter A Block, Red Diner Alphabet 2, Staircase 26 - on its catalog row and
-- its furniture row's public_name; the pages with Spanish or placeholder
-- captions are renamed (Cradle____ holds the Wedge). The same names go to
-- FurnitureData through nitro/overrides/gamedata-override/FurnitureData.json,
-- which is what rooms, backpacks and the infostand read.
--
-- Rows are matched by furniture id (93's fixed 104297-104529) and classname
-- together, so nothing outside the line can be caught. Idempotent.

