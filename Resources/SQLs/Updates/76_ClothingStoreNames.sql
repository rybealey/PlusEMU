  JOIN `rp_clothing_rename` r
    ON r.`shelf_key` = CONVERT(LOWER(TRIM(REGEXP_REPLACE(IF(LEFT(c.`clothing_name`, 9) = 'clothing_', SUBSTRING(c.`clothing_name`, 10), c.`clothing_name`), '[_[:space:]]+', ' '))) USING utf8mb4) COLLATE utf8mb4_general_ci
   SET c.`display_name` = r.`proposed`
 WHERE c.`display_name` IS NULL;

SELECT CONCAT('clothing pieces now named: ', COUNT(*)) AS `receipt`
  FROM `catalog_clothing` WHERE `display_name` IS NOT NULL;

-- Pieces still on a placeholder: either added to the store after the
-- capture, or renamed by hand in between.
SELECT CONCAT('still unnamed and on sale: ', COUNT(*)) AS `receipt`
  FROM `catalog_clothing` WHERE `display_name` IS NULL AND `price` > 0;

-- Renames that found nothing to apply to.
SELECT CONCAT('no such piece: ', r.`shelf_key`) AS `receipt`
  FROM `rp_clothing_rename` r
  LEFT JOIN `catalog_clothing` c ON CONVERT(LOWER(TRIM(REGEXP_REPLACE(IF(LEFT(c.`clothing_name`, 9) = 'clothing_', SUBSTRING(c.`clothing_name`, 10), c.`clothing_name`), '[_[:space:]]+', ' '))) USING utf8mb4) COLLATE utf8mb4_general_ci = r.`shelf_key`
 WHERE c.`id` IS NULL;

