-- pixelrp: the Spaces page sells floors and wallpapers again.
--
-- On beta the page (layout 'spaces_new') served its 48 landscapes and nothing
-- else: the client logged 48 offers, all landscape, so the Floors and Walls
-- tabs were empty. Every migration that ever touched the page wrote the floor
-- and wallpaper rows the same way as the landscape ones, so whatever removed
-- them was done on the database by hand - this puts them back in a known
-- state rather than guessing what happened.
--
-- 1. The two furniture rows they sell - 19894 (floor, sprite 3002) and 19896
--    (wallpaper, sprite 3001) - are made sure of, as in the base dump. If a
--    row is there, only the fields the shop and the room decoration read are
--    restored; its names are left alone.
-- 2. Every floor and wallpaper row on the page is replaced with one per pattern
--    the client can actually draw: the planes in room.nitro's floorData and
--    wallData (57 floors, 160 wallpapers; the '99999' test wall left out). The
--    old list had wallpaper 2207, which room.nitro does not have, missed floors
--    212 and 603, and carried nine repeats.
--
-- Landscapes are not touched. Free, per 90_FreeCatalog. The offer ids are the
-- base dump's (9874 floors, 9714 wallpapers), which legacy links resolve.
--
-- Idempotent: the floor and wallpaper rows are cleared before insert.

SET @spaces := (SELECT `id` FROM `catalog_pages` WHERE `page_layout` = 'spaces_new' ORDER BY `id` LIMIT 1);

INSERT INTO `furniture` (`id`,`item_name`,`public_name`,`type`,`width`,`length`,`stack_height`,`can_stack`,`can_sit`,`is_walkable`,`sprite_id`,`allow_recycle`,`allow_trade`,`allow_marketplace_sell`,`allow_gift`,`allow_inventory_stack`,`interaction_type`,`behaviour_data`,`interaction_modes_count`) VALUES
    (19894,'a2 l','Floor','i',1,1,1,'1','0','0',3002,'0','0','1','1','0','floor',0,1),
    (19896,'wallpaper 1','Wallpaper','i',1,1,1,'1','0','0',3001,'0','0','1','1','0','wallpaper',0,1)
ON DUPLICATE KEY UPDATE `type` = VALUES(`type`), `sprite_id` = VALUES(`sprite_id`),
    `interaction_type` = VALUES(`interaction_type`);

DELETE FROM `catalog_items` WHERE `page_id` = @spaces AND `item_id` IN ('19894','19896');

